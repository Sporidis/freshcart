import 'package:freshcart_domain/src/core/failure.dart';
import 'package:meta/meta.dart';

/// The outcome of an operation that can fail in an expected way: either an
/// [Ok] carrying a value, or an [Err] carrying a [Failure].
///
/// Every repository port and use case returns one of these. Because [Result]
/// is `sealed`, a `switch` over it is checked for exhaustiveness by the
/// compiler, so a newly added case cannot be silently ignored:
///
/// ```dart
/// final message = switch (result) {
///   Ok(:final value) => 'Added ${value.name}',
///   Err(:final failure) => failure.toMessage(),
/// };
/// ```
///
/// This is deliberately hand-written rather than generated by `freezed`. See
/// `docs/decisions.md` #16.
@immutable
sealed class Result<T> {
  /// Const superclass constructor for the two variants.
  const Result();

  /// Wraps a successful [value].
  const factory Result.ok(T value) = Ok<T>;

  /// Wraps an expected [failure].
  const factory Result.err(Failure failure) = Err<T>;

  /// Whether this is an [Ok].
  bool get isOk => this is Ok<T>;

  /// Whether this is an [Err].
  bool get isErr => this is Err<T>;

  /// The value if this is an [Ok], otherwise `null`.
  ///
  /// Prefer a `switch` where you must handle both cases; this is for the times
  /// a missing value is genuinely uninteresting.
  T? get valueOrNull => switch (this) {
    Ok<T>(:final value) => value,
    Err<T>() => null,
  };

  /// The failure if this is an [Err], otherwise `null`.
  Failure? get failureOrNull => switch (this) {
    Ok<T>() => null,
    Err<T>(:final failure) => failure,
  };

  /// Collapses both variants into a single [R].
  ///
  /// The workhorse for turning a [Result] into UI state.
  R fold<R>({
    required R Function(T value) ok,
    required R Function(Failure failure) err,
  }) => switch (this) {
    Ok<T>(value: final v) => ok(v),
    Err<T>(failure: final f) => err(f),
  };

  /// Transforms the value of an [Ok], leaving an [Err] untouched.
  Result<R> map<R>(R Function(T value) transform) => switch (this) {
    Ok<T>(value: final v) => Ok<R>(transform(v)),
    Err<T>(failure: final f) => Err<R>(f),
  };

  /// Chains another fallible operation, short-circuiting on the first [Err].
  ///
  /// Lets a use case sequence several repository calls without a pyramid of
  /// `if (result.isErr) return ...`.
  Result<R> flatMap<R>(Result<R> Function(T value) transform) => switch (this) {
    Ok<T>(value: final v) => transform(v),
    Err<T>(failure: final f) => Err<R>(f),
  };
}

/// A successful [Result] carrying [value].
@immutable
final class Ok<T> extends Result<T> {
  /// Wraps a successful [value].
  const Ok(this.value);

  /// The produced value.
  final T value;

  @override
  bool operator ==(Object other) =>
      identical(this, other) || other is Ok<T> && other.value == value;

  @override
  int get hashCode => Object.hash(Ok<T>, value);

  @override
  String toString() => 'Ok<$T>($value)';
}

/// A failed [Result] carrying [failure].
@immutable
final class Err<T> extends Result<T> {
  /// Wraps an expected [failure].
  const Err(this.failure);

  /// Why the operation did not produce a value.
  final Failure failure;

  @override
  bool operator ==(Object other) =>
      identical(this, other) || other is Err<T> && other.failure == failure;

  @override
  int get hashCode => Object.hash(Err<T>, failure);

  @override
  String toString() => 'Err<$T>($failure)';
}
